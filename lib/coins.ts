export function gapPct(coin: Coin) {
  if (!coin.mcapRobinhood || !coin.mcapSolana) return 0;
  const mid = (coin.mcapRobinhood + coin.mcapSolana) / 2;
  return (Math.abs(coin.mcapRobinhood - coin.mcapSolana) / mid) * 100;
}

